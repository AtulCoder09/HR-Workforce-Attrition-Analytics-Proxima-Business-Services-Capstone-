/* KPI - 3 */
SELECT 
    ROUND(
        (
            COUNT(DISTINCT CASE 
                WHEN d.IS_PEOPLE_MANAGER = 'Yes' 
                 AND e.GENDER = 'Female' 
                 AND e.EMPLOYMENT_STATUS IN ('Active', 'Serving Notice') 
                THEN e.EMPLOYEE_ID 
            END)
            /
            NULLIF(
                COUNT(DISTINCT CASE 
                    WHEN d.IS_PEOPLE_MANAGER = 'Yes' 
                     AND e.EMPLOYMENT_STATUS IN ('Active', 'Serving Notice') 
                    THEN e.EMPLOYEE_ID 
                END), 
                0
            )
        ) * 100, 
        2
    ) AS women_in_leadership_pct
FROM EMPLOYEES e
JOIN DESIGNATIONS d ON e.DESIGNATION_ID = d.DESIGNATION_ID;


/* KPI - 4 */
SELECT 
    ROUND(
        (
            COUNT(DISTINCT CASE 
                WHEN ex.REGRETTABLE_ATTRITION = 'Yes' 
                THEN ex.EMPLOYEE_ID 
            END)
            /
            NULLIF(COUNT(DISTINCT e.EMPLOYEE_ID), 0)
        ) * 100, 
        2
    ) AS regrettable_attrition_rate_pct
FROM EMPLOYEES e
LEFT JOIN EXIT_DETAILS ex ON e.EMPLOYEE_ID = ex.EMPLOYEE_ID;

/* KPI - 5 */
SELECT 
    IFNULL(CAST(hire_year AS CHAR), 'Grand Total') AS hire_year,
    employee_count
FROM (
    SELECT 
        YEAR(HIRE_DATE) AS hire_year,
        COUNT(EMPLOYEE_ID) AS employee_count
    FROM EMPLOYEES
    WHERE HIRE_DATE IS NOT NULL
    GROUP BY YEAR(HIRE_DATE) WITH ROLLUP
) AS t
ORDER BY (hire_year IS NULL) ASC, hire_year DESC;


/* KPI - 6 */
SELECT 
    IFNULL(department_name, 'Grand Total') AS department_name,
    employee_count
FROM (
    SELECT 
        d.DEPARTMENT_NAME AS department_name,
        COUNT(e.EMPLOYEE_ID) AS employee_count
    FROM EMPLOYEES e
    JOIN DEPARTMENTS d ON e.DEPARTMENT_ID = d.DEPARTMENT_ID
    GROUP BY d.DEPARTMENT_NAME WITH ROLLUP
) AS t
ORDER BY (department_name IS NULL) ASC, employee_count DESC;


